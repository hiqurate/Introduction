async function migrate(db) {
  await db.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    applied_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  )`);
  const applied = new Set((await db.all('SELECT id FROM schema_migrations')).map(r => r.id));
  for (const m of MIGRATIONS) {
    if (applied.has(m.id)) continue;
    try {
      await db.transaction(async tx => {
        await tx.exec(m.sql);
        await tx.run('INSERT INTO schema_migrations (id, name) VALUES (?, ?)', [m.id, m.name]);
      });
    } catch (err) {
      throw new Error(`Migration ${m.id} (${m.name}) failed: ${err.message}`);
    }
  }
}

async function openPostgres(url) {
  const db = new PgDatabase(url);
  await db.withLock(() => migrate(db));
  return db;
}

