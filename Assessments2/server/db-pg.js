// ============================================
// HawkSight — Postgres database (Neon and other hosted Postgres)
// Same interface as the SQLite wrapper in db.js, so routes and services run
// unchanged. Queries are written with "?" placeholders and translated here.
// ============================================

const { Pool, types } = require('pg');

// Return counts and sums as numbers, as SQLite does.
types.setTypeParser(20, v => (v === null ? null : parseInt(v, 10)));     // int8 (COUNT, SUM)
types.setTypeParser(1700, v => (v === null ? null : parseFloat(v)));     // numeric (AVG)

// Arbitrary constant identifying the HawkSight migration lock.
const LOCK_ID = 727472001;

// Translate "?" placeholders to $1, $2 ... outside quoted strings.
function translate(sql) {
  let out = '';
  let n = 0;
  let quote = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (quote) {
      out += ch;
      if (ch === quote) quote = null;
    } else if (ch === '\'' || ch === '"') {
      quote = ch;
      out += ch;
    } else if (ch === '?') {
      out += `$${++n}`;
    } else {
      out += ch;
    }
  }
  return out;
}

// Inserts return the new row so callers get lastID, as with SQLite.
function withReturning(sql) {
  return /^\s*INSERT\b/i.test(sql) && !/\bRETURNING\b/i.test(sql) ? `${sql.replace(/;\s*$/, '')} RETURNING *` : sql;
}

class PgQueryable {
  constructor(client) {
    this.client = client;
    this.dialect = 'postgres';
  }

  async run(sql, params = []) {
    const res = await this.client.query(withReturning(translate(sql)), params);
    const row = res.rows && res.rows[0];
    return { lastID: row ? (row.id !== undefined ? row.id : row.version) : undefined, changes: res.rowCount };
  }

  async get(sql, params = []) {
    const res = await this.client.query(translate(sql), params);
    return res.rows[0];
  }

  async all(sql, params = []) {
    const res = await this.client.query(translate(sql), params);
    return res.rows;
  }

  // Multi-statement SQL without parameters (migrations).
  async exec(sql) {
    await this.client.query(sql);
  }
}

class PgDatabase extends PgQueryable {
  constructor(url) {
    const pool = new Pool({
      connectionString: url,
      max: Number(process.env.PG_POOL_MAX) || 5,
      idleTimeoutMillis: 10000,
      connectionTimeoutMillis: 10000
    });
    super(pool);
    this.pool = pool;
    // A dropped idle connection must not crash the process.
    pool.on('error', err => console.error('Postgres pool error:', err.message));
  }

  async transaction(fn) {
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      const result = await fn(new PgQueryable(client));
      await client.query('COMMIT');
      return result;
    } catch (err) {
      await client.query('ROLLBACK').catch(() => {});
      throw err;
    } finally {
      client.release();
    }
  }

  // Serialises start-up work (migrations, first-run seeding) across
  // concurrently starting serverless instances.
  async withLock(fn) {
    const client = await this.pool.connect();
    try {
      await client.query('SELECT pg_advisory_lock($1)', [LOCK_ID]);
      return await fn();
    } finally {
      await client.query('SELECT pg_advisory_unlock($1)', [LOCK_ID]).catch(() => {});
      client.release();
    }
  }

  close() {
    return this.pool.end();
  }
}

